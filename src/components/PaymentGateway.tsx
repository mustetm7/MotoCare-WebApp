import React, { useState } from 'react';
import { PaymentMethod } from '../types';
import {
  Smartphone,
  Download,
  Copy,
  Check,
  ExternalLink,
  ShieldCheck,
  Clock,
  Send,
  Zap,
  CheckCircle2,
  Share2,
} from 'lucide-react';
import { sounds } from '../utils/audio';

interface PaymentGatewayProps {
  planAmount?: number;
  onSubmitReference: (method: PaymentMethod, referenceNumber: string) => void;
  onClose: () => void;
  isAlreadyPending?: boolean;
  existingPendingRef?: string;
}

export const PaymentGateway: React.FC<PaymentGatewayProps> = ({
  planAmount = 49,
  onSubmitReference,
  onClose,
  isAlreadyPending = false,
  existingPendingRef,
}) => {
  const [selectedMethod, setSelectedMethod] = useState<'gcash' | 'gotyme'>('gcash');
  const [referenceNumber, setReferenceNumber] = useState('');
  const [copiedAccount, setCopiedAccount] = useState(false);
  const [copiedRef, setCopiedRef] = useState(false);
  const [qrSaved, setQrSaved] = useState(false);
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [hasSubmitted, setHasSubmitted] = useState(isAlreadyPending);
  const [submittedRef, setSubmittedRef] = useState(existingPendingRef || '');

  // Provider specifications matching Philippine Payment Gateway standards
  const providers = {
    gcash: {
      name: 'GCash',
      type: 'E-Wallet',
      brandColor: '#007DFE',
      activeTabClass: 'bg-[#007DFE] text-white shadow-md shadow-blue-500/25',
      badgeBg: 'bg-blue-50 text-blue-700 border-blue-200',
      accountName: 'Official GCash / QRPH Merchant',
      accountNumber: '0917-889-4921',
      qrPrompt: 'Scan with GCash or any InstaPay / QRPH banking app',
      tagline: 'Official GCash InstaPay QRPH',
      qrImage: '/assets/aistudio/gcash_37c30549.jpg',
      appScheme: 'gcash://',
      appIntent: 'intent://#Intent;scheme=gcash;package=com.globe.gcash.android;end',
    },
    gotyme: {
      name: 'GoTyme Bank',
      type: 'Digital Bank',
      brandColor: '#00BFA5',
      activeTabClass: 'bg-[#00BFA5] text-white shadow-md shadow-teal-500/25',
      badgeBg: 'bg-teal-50 text-teal-800 border-teal-200',
      accountName: 'MotoCare PH (GoTyme Bank Account)',
      accountNumber: '0124-8839-2041',
      qrPrompt: 'Scan with GoTyme Bank App or any QRPH app',
      tagline: 'Zero-Fee QRPH Bank Transfer',
      qrImage: null, // Renders dedicated GoTyme InstaPay QRPH interface
      appScheme: 'gotyme://',
      appIntent: 'gotyme://',
    },
  };

  const currentProvider = providers[selectedMethod];
  const autoGeneratedRef = `MC-${selectedMethod.toUpperCase()}-${Math.floor(100000 + Math.random() * 900000)}`;

  // Tool 1: Open Payment App Deep Link
  const handleOpenApp = () => {
    sounds.playClick();
    const isAndroid = /android/i.test(navigator.userAgent);
    if (selectedMethod === 'gcash' && isAndroid) {
      window.location.href = currentProvider.appIntent;
    } else {
      window.location.href = currentProvider.appScheme;
    }
  };

  // Tool 2: Save QR Photo to Gallery
  const handleSaveQr = () => {
    sounds.playSuccess();
    const link = document.createElement('a');
    if (selectedMethod === 'gcash') {
      link.href = '/assets/aistudio/gcash_37c30549.jpg';
      link.download = 'MotoCare-GCash-QR.jpg';
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
    } else {
      // Download GoTyme InstaPay QRPH SVG
      const gotymeSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 300 300" width="300" height="300">
        <rect width="300" height="300" fill="#ffffff" rx="24"/>
        <text x="150" y="36" font-family="system-ui, sans-serif" font-weight="900" font-size="15" fill="#00BFA5" text-anchor="middle">GOTYME BANK INSTAPAY QRPH</text>
        <rect x="25" y="48" width="250" height="240" fill="#f8fafc" rx="16" stroke="#e2e8f0" stroke-width="2"/>
        <rect x="45" y="68" width="56" height="56" rx="10" fill="none" stroke="#0f172a" stroke-width="12"/>
        <rect x="61" y="84" width="24" height="24" rx="4" fill="#0f172a"/>
        <rect x="199" y="68" width="56" height="56" rx="10" fill="none" stroke="#0f172a" stroke-width="12"/>
        <rect x="215" y="84" width="24" height="24" rx="4" fill="#0f172a"/>
        <rect x="45" y="210" width="56" height="56" rx="10" fill="none" stroke="#0f172a" stroke-width="12"/>
        <rect x="61" y="226" width="24" height="24" rx="4" fill="#0f172a"/>
        <circle cx="150" cy="150" r="26" fill="#00BFA5"/>
        <text x="150" y="157" font-family="system-ui, sans-serif" font-weight="900" font-size="18" fill="#ffffff" text-anchor="middle">Go</text>
      </svg>`;
      const blob = new Blob([gotymeSvg], { type: 'image/svg+xml' });
      const url = URL.createObjectURL(blob);
      link.href = url;
      link.download = 'MotoCare-GoTyme-QRPH.svg';
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      setTimeout(() => URL.revokeObjectURL(url), 1000);
    }
    setQrSaved(true);
    setTimeout(() => setQrSaved(false), 2500);
  };

  // Tool 3: One-Click Copy Account Number
  const handleCopyAccount = () => {
    navigator.clipboard?.writeText(currentProvider.accountNumber);
    sounds.playClick();
    setCopiedAccount(true);
    setTimeout(() => setCopiedAccount(false), 2000);
  };

  // Tool 3: One-Click Copy Reference Code
  const handleCopyRef = () => {
    navigator.clipboard?.writeText(autoGeneratedRef);
    sounds.playClick();
    setCopiedRef(true);
    setTimeout(() => setCopiedRef(false), 2000);
  };

  // Submission handler for admin verification
  const handleSubmitForVerification = () => {
    setIsSubmitting(true);
    sounds.playClick();

    const finalRef = referenceNumber.trim() || autoGeneratedRef;

    setTimeout(() => {
      setIsSubmitting(false);
      setSubmittedRef(finalRef);
      setHasSubmitted(true);
      sounds.playSuccess();
      onSubmitReference(selectedMethod, finalRef);
    }, 700);
  };

  // Submitted / Pending State
  if (hasSubmitted) {
    return (
      <div className="p-5 bg-amber-50 border border-amber-200 rounded-3xl text-left space-y-3.5 animate-in fade-in">
        <div className="flex items-center gap-3">
          <div className="w-10 h-10 rounded-2xl bg-amber-200/80 text-amber-800 flex items-center justify-center shrink-0">
            <Clock className="w-5 h-5 animate-pulse" />
          </div>
          <div>
            <div className="text-sm font-extrabold text-amber-900">
              Payment Reference Submitted
            </div>
            <div className="text-xs text-amber-700 font-semibold">
              Status: Pending Owner Verification
            </div>
          </div>
        </div>

        <div className="p-3.5 bg-white/95 rounded-2xl border border-amber-200/80 text-xs space-y-2 shadow-2xs">
          <div className="flex justify-between items-center">
            <span className="text-slate-500 font-medium">Reference Code:</span>
            <span className="font-mono font-black text-slate-800 text-xs">
              {submittedRef || autoGeneratedRef}
            </span>
          </div>
          <div className="flex justify-between items-center">
            <span className="text-slate-500 font-medium">Amount:</span>
            <span className="font-extrabold text-emerald-700 font-mono text-sm">₱{planAmount}.00</span>
          </div>
          <div className="flex justify-between items-center">
            <span className="text-slate-500 font-medium">Payment Channel:</span>
            <span className="font-bold text-slate-800 uppercase">{selectedMethod}</span>
          </div>
        </div>

        <p className="text-xs text-amber-800 leading-relaxed">
          Thank you! Your reference has been submitted. The owner will verify your {currentProvider.name} transfer in the separate <strong>Admin Panel</strong> to approve your Pro access.
        </p>

        <div className="pt-1 flex gap-2">
          <button
            type="button"
            onClick={() => setHasSubmitted(false)}
            className="flex-1 py-2.5 bg-white hover:bg-slate-50 text-slate-700 border border-slate-200 rounded-xl font-bold text-xs transition-colors cursor-pointer"
          >
            Submit Another Ref
          </button>
          <button
            type="button"
            onClick={onClose}
            className="flex-1 py-2.5 bg-slate-900 hover:bg-black text-white rounded-xl font-bold text-xs transition-all active:scale-95 shadow-sm cursor-pointer"
          >
            Return to Garage
          </button>
        </div>
      </div>
    );
  }

  return (
    <div className="space-y-4">
      {/* Dynamic Payment Method Switcher Tabs (GCash & GoTyme) */}
      <div className="space-y-1.5 text-left">
        <label className="text-[11px] font-bold text-slate-500 uppercase tracking-wider">
          Choose QR Payment Method:
        </label>
        <div className="grid grid-cols-2 gap-2 p-1 bg-slate-100 rounded-2xl">
          <button
            type="button"
            onClick={() => {
              sounds.playClick();
              setSelectedMethod('gcash');
            }}
            className={`py-2.5 px-3 rounded-xl font-bold text-xs flex items-center justify-center gap-2 transition-all cursor-pointer ${
              selectedMethod === 'gcash'
                ? providers.gcash.activeTabClass
                : 'text-slate-600 hover:text-slate-900 hover:bg-slate-200/60'
            }`}
          >
            <span className="w-2.5 h-2.5 rounded-full bg-white/80 shrink-0" />
            <span>GCash QR</span>
          </button>

          <button
            type="button"
            onClick={() => {
              sounds.playClick();
              setSelectedMethod('gotyme');
            }}
            className={`py-2.5 px-3 rounded-xl font-bold text-xs flex items-center justify-center gap-2 transition-all cursor-pointer ${
              selectedMethod === 'gotyme'
                ? providers.gotyme.activeTabClass
                : 'text-slate-600 hover:text-slate-900 hover:bg-slate-200/60'
            }`}
          >
            <span className="w-2.5 h-2.5 rounded-full bg-white/80 shrink-0" />
            <span>GoTyme Bank</span>
          </button>
        </div>
      </div>

      {/* Dynamic QR Display Card */}
      <div className="p-4 sm:p-5 bg-slate-50 border border-slate-200/90 rounded-3xl text-center space-y-4 shadow-xs">
        {/* Gateway Header Badge */}
        <div className="flex items-center justify-between pb-2 border-b border-slate-200/70">
          <div className="flex items-center gap-2 text-left">
            <div
              className="w-7 h-7 rounded-lg text-white font-black text-xs flex items-center justify-center shadow-xs"
              style={{ backgroundColor: currentProvider.brandColor }}
            >
              {selectedMethod === 'gcash' ? 'G' : 'Go'}
            </div>
            <div>
              <div className="font-extrabold text-xs sm:text-sm text-slate-900 leading-tight">
                {currentProvider.name} QRPH Code
              </div>
              <div className="text-[10px] text-slate-400 font-medium">
                {currentProvider.tagline}
              </div>
            </div>
          </div>

          <span className="text-[10px] font-bold px-2 py-0.5 rounded-full bg-blue-50 text-blue-700 border border-blue-200 flex items-center gap-1 shrink-0">
            <Zap className="w-2.5 h-2.5 fill-blue-600 text-blue-600" />
            <span>QRPH Official</span>
          </span>
        </div>

        {/* Dynamic QR Code Viewport */}
        {selectedMethod === 'gcash' ? (
          /* GCash: Official Uploaded QRPH Image */
          <div className="space-y-1.5">
            <div className="relative mx-auto w-56 h-56 bg-white p-2.5 rounded-2xl border-2 border-[#007DFE]/40 shadow-md flex items-center justify-center overflow-hidden group">
              <img
                src="/assets/aistudio/gcash_37c30549.jpg"
                alt="Official GCash QR Code"
                className="w-full h-full object-contain rounded-xl select-none"
              />
              <div className="absolute bottom-1.5 left-2 right-2 py-0.5 bg-white/95 backdrop-blur-xs rounded-lg border border-slate-200/80 text-[9px] font-black text-slate-700 flex items-center justify-center gap-1 shadow-2xs">
                <span className="text-red-500 font-black">Insta</span>
                <span className="text-blue-600 font-black">Pay</span>
                <span className="text-slate-300">•</span>
                <span className="text-[#007DFE] font-bold">GCash QRPH</span>
              </div>
            </div>
            <div className="text-[10px] font-bold text-blue-700 bg-blue-50/80 py-1 px-3 rounded-full mx-auto w-fit border border-blue-200/60">
              ✓ Connected Official GCash QRPH Code
            </div>
          </div>
        ) : (
          /* GoTyme Bank: Dedicated InstaPay QRPH Transfer Interface */
          <div className="space-y-1.5">
            <div className="relative mx-auto w-56 h-56 bg-white p-3 rounded-2xl border-2 border-[#00BFA5]/50 shadow-md flex flex-col items-center justify-center overflow-hidden">
              <svg className="w-44 h-44 text-slate-900" viewBox="0 0 100 100" fill="currentColor">
                {/* Corner Finder Patterns */}
                <rect x="4" y="4" width="26" height="26" rx="4" fill="none" stroke="currentColor" strokeWidth="6" />
                <rect x="11" y="11" width="12" height="12" rx="2" />
                <rect x="70" y="4" width="26" height="26" rx="4" fill="none" stroke="currentColor" strokeWidth="6" />
                <rect x="77" y="11" width="12" height="12" rx="2" />
                <rect x="4" y="70" width="26" height="26" rx="4" fill="none" stroke="currentColor" strokeWidth="6" />
                <rect x="11" y="77" width="12" height="12" rx="2" />

                {/* QR Data Matrix simulation */}
                <rect x="36" y="8" width="6" height="6" />
                <rect x="48" y="8" width="6" height="6" />
                <rect x="58" y="8" width="6" height="6" />
                <rect x="36" y="20" width="6" height="6" />
                <rect x="52" y="20" width="6" height="6" />
                <rect x="8" y="36" width="6" height="6" />
                <rect x="20" y="36" width="6" height="6" />
                <rect x="36" y="36" width="6" height="6" />
                <rect x="58" y="36" width="6" height="6" />
                <rect x="76" y="36" width="6" height="6" />
                <rect x="86" y="36" width="6" height="6" />
                <rect x="8" y="48" width="6" height="6" />
                <rect x="26" y="48" width="6" height="6" />
                <rect x="68" y="48" width="6" height="6" />
                <rect x="84" y="48" width="6" height="6" />
                <rect x="36" y="60" width="6" height="6" />
                <rect x="52" y="60" width="6" height="6" />
                <rect x="74" y="60" width="6" height="6" />
                <rect x="36" y="76" width="6" height="6" />
                <rect x="48" y="76" width="6" height="6" />
                <rect x="64" y="76" width="6" height="6" />
                <rect x="82" y="76" width="6" height="6" />
                <rect x="40" y="88" width="6" height="6" />
                <rect x="60" y="88" width="6" height="6" />
                <rect x="76" y="88" width="6" height="6" />
              </svg>

              {/* GoTyme Center Emblem */}
              <div className="absolute inset-auto w-11 h-11 rounded-xl p-1 bg-white shadow-lg flex items-center justify-center border-2 border-white">
                <div className="w-full h-full rounded-lg bg-[#00BFA5] text-white font-black text-xs flex items-center justify-center shadow-inner">
                  Go
                </div>
              </div>

              {/* InstaPay Bottom Badge */}
              <div className="absolute bottom-1.5 left-2 right-2 py-0.5 bg-white/95 backdrop-blur-xs rounded-lg border border-slate-200/80 text-[9px] font-black text-slate-700 flex items-center justify-center gap-1 shadow-2xs">
                <span className="text-red-500 font-black">Insta</span>
                <span className="text-blue-600 font-black">Pay</span>
                <span className="text-slate-300">•</span>
                <span className="text-[#00BFA5] font-bold">GoTyme QRPH</span>
              </div>
            </div>
            <div className="text-[10px] font-bold text-teal-800 bg-teal-50/80 py-1 px-3 rounded-full mx-auto w-fit border border-teal-200/60">
              ✓ GoTyme Bank InstaPay QRPH Active
            </div>
          </div>
        )}

        {/* Dynamic Amount Banner */}
        <div className="flex items-center justify-between p-2.5 bg-white rounded-xl border border-slate-200/80 text-xs shadow-2xs">
          <span className="text-slate-500 font-medium">Subscription Amount:</span>
          <div className="font-extrabold text-base text-slate-900 font-mono flex items-baseline gap-1">
            <span className="text-[#FF6B00]">₱{planAmount}.00</span>
            <span className="text-[10px] text-slate-400 font-normal">/ month</span>
          </div>
        </div>

        {/* Instant Mobile Tools: Open App & Save QR Photo */}
        <div className="space-y-1.5 text-left">
          <div className="text-[11px] font-bold text-slate-500 uppercase tracking-wider">
            Instant Mobile Tools:
          </div>
          <div className="grid grid-cols-2 gap-2">
            {/* Tool 1: Open Payment App */}
            <button
              type="button"
              onClick={handleOpenApp}
              className="py-2.5 px-3 rounded-xl bg-slate-900 hover:bg-black text-white font-bold text-xs flex items-center justify-center gap-1.5 shadow-sm transition-all active:scale-95 cursor-pointer"
              title={`Direct deep-link to launch ${currentProvider.name} on this phone`}
            >
              <Smartphone className="w-3.5 h-3.5 text-cyan-400" />
              <span>Open {currentProvider.name}</span>
              <ExternalLink className="w-3 h-3 opacity-70" />
            </button>

            {/* Tool 2: Save QR Photo */}
            <button
              type="button"
              onClick={handleSaveQr}
              className="py-2.5 px-3 rounded-xl bg-white hover:bg-slate-100 border border-slate-200 text-slate-800 font-bold text-xs flex items-center justify-center gap-1.5 shadow-2xs transition-all active:scale-95 cursor-pointer"
              title="Download QR code directly to your phone gallery for easy scanning"
            >
              {qrSaved ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Download className="w-3.5 h-3.5 text-[#FF6B00]" />}
              <span>{qrSaved ? 'Saved to Photos!' : 'Save QR Photo'}</span>
            </button>
          </div>
        </div>

        {/* Tool 3: One-Click Copy Account & Reference */}
        <div className="space-y-2 text-xs text-left pt-1">
          {/* Account Number Card */}
          <div className="p-2.5 bg-white rounded-xl border border-slate-200/80 flex items-center justify-between">
            <div>
              <span className="text-[10px] text-slate-400 font-bold uppercase">Account / Mobile No:</span>
              <div className="font-mono font-extrabold text-slate-800 text-xs">
                {currentProvider.accountNumber}
              </div>
              <div className="text-[10px] text-slate-500">{currentProvider.accountName}</div>
            </div>
            <button
              type="button"
              onClick={handleCopyAccount}
              className="px-2.5 py-1 rounded-lg bg-slate-50 border border-slate-200 text-slate-700 text-[11px] font-bold hover:bg-slate-100 flex items-center gap-1 shadow-2xs shrink-0 cursor-pointer"
            >
              {copiedAccount ? <Check className="w-3.5 h-3.5 text-emerald-600" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copiedAccount ? 'Copied' : 'Copy No.'}</span>
            </button>
          </div>

          {/* Reference Input & One-Click Copy */}
          <div className="space-y-1">
            <div className="flex items-center justify-between text-[11px]">
              <label className="font-bold text-slate-700">
                Payment Reference Number:
              </label>
              <button
                type="button"
                onClick={handleCopyRef}
                className="text-[10px] font-bold text-[#FF6B00] hover:underline flex items-center gap-0.5 cursor-pointer"
                title="Copy and use generated reference"
              >
                <span>{copiedRef ? 'Copied!' : 'Auto-Generate Ref'}</span>
              </button>
            </div>
            <input
              type="text"
              value={referenceNumber}
              onChange={(e) => setReferenceNumber(e.target.value)}
              placeholder={`e.g. 104829482 or ${autoGeneratedRef}`}
              className="w-full bg-white border border-slate-200 rounded-xl px-3 py-2 text-xs font-mono font-bold text-slate-800 focus:outline-none focus:border-[#FF6B00] focus:ring-1 focus:ring-[#FF6B00]/20"
            />
          </div>
        </div>
      </div>

      {/* Submit for Owner Verification Button */}
      <div className="space-y-2">
        <button
          type="button"
          disabled={isSubmitting}
          onClick={handleSubmitForVerification}
          className="w-full py-3.5 bg-[#FF6B00] hover:bg-[#EA580C] text-white rounded-2xl font-black text-sm shadow-lg shadow-[#FF6B00]/25 transition-all active:scale-98 flex items-center justify-center gap-2 disabled:opacity-50 cursor-pointer"
        >
          {isSubmitting ? (
            <>
              <div className="w-4 h-4 border-2 border-white border-t-transparent rounded-full animate-spin" />
              <span>Forwarding Reference to Owner...</span>
            </>
          ) : (
            <>
              <Send className="w-4 h-4" />
              <span>Submit Reference for Admin Verification (₱{planAmount})</span>
            </>
          )}
        </button>

        <div className="flex items-center justify-center gap-1.5 text-[10px] text-slate-400">
          <ShieldCheck className="w-3.5 h-3.5 text-slate-400" />
          <span>Manual verification: Owner approves payment in the separate Admin Console.</span>
        </div>
      </div>
    </div>
  );
};
