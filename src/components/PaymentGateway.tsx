import React, { useState } from 'react';
import { PaymentMethod } from '../types';
import {
  Smartphone,
  Download,
  Copy,
  Check,
  ExternalLink,
  ShieldCheck,
  Clock,
  Send,
  Zap,
  CheckCircle2,
  Share2,
  AlertCircle,
  Lock,
  Mail,
  X,
  UserCheck,
} from 'lucide-react';
import { sounds } from '../utils/audio';
import { useAuth } from '../context/AuthContext';

interface PaymentGatewayProps {
  planAmount?: number;
  onSubmitReference: (method: PaymentMethod, referenceNumber: string) => void | Promise<void>;
  onClose: () => void;
  isAlreadyPending?: boolean;
  existingPendingRef?: string;
  autoDownloadedQr?: boolean;
  qrBlobUrl?: string;
  onDownloadQrCode?: () => void;
  onScanQrCode?: () => void;
}

export const PaymentGateway: React.FC<PaymentGatewayProps> = ({
  planAmount = 49,
  onSubmitReference,
  onClose,
  isAlreadyPending = false,
  existingPendingRef,
  autoDownloadedQr = false,
  qrBlobUrl,
  onDownloadQrCode,
}) => {
  const { user, signIn, signInWithEmail, signUpWithEmail } = useAuth();

  const selectedMethod: PaymentMethod = 'gcash';
  const [autoGeneratedRef, setAutoGeneratedRef] = useState(
    () => `MC-GCASH-${Math.floor(100000 + Math.random() * 900000)}`
  );
  const [referenceNumber, setReferenceNumber] = useState('');
  const [copiedRef, setCopiedRef] = useState(false);
  const [qrSaved, setQrSaved] = useState(autoDownloadedQr);
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [hasSubmitted, setHasSubmitted] = useState(isAlreadyPending);
  const [submittedRef, setSubmittedRef] = useState(existingPendingRef || '');
  const [submissionError, setSubmissionError] = useState('');
  const hiddenDownloadLinkRef = React.useRef<HTMLAnchorElement | null>(null);

  // Sign-in prompt modal state when rider is not logged in
  const [isAuthModalOpen, setIsAuthModalOpen] = useState(false);
  const [authMode, setAuthMode] = useState<'signin' | 'register'>('signin');
  const [authEmail, setAuthEmail] = useState('');
  const [authPassword, setAuthPassword] = useState('');
  const [authDisplayName, setAuthDisplayName] = useState('');
  const [authModalError, setAuthModalError] = useState('');
  const [isAuthProcessing, setIsAuthProcessing] = useState(false);

  const gcashProvider = {
    name: 'GCash',
    brandColor: '#007DFE',
    tagline: 'Official GCash InstaPay QRPH',
    qrImage: '/assets/aistudio/gcash_37c30549.jpg',
    appScheme: 'gcash://',
    appIntent: 'intent://#Intent;scheme=gcash;package=com.globe.gcash.android;end',
  };

  React.useEffect(() => {
    if (autoDownloadedQr) {
      setQrSaved(true);
    }
  }, [autoDownloadedQr]);

  // Tool 1: Open GCash App Deep Link
  const handleOpenApp = () => {
    sounds.playClick();
    const isAndroid = /android/i.test(navigator.userAgent);
    if (isAndroid) {
      window.location.href = gcashProvider.appIntent;
    } else {
      window.location.href = gcashProvider.appScheme;
    }
  };

  // Tool 2: Save GCash QR Image to Gallery via hidden anchor and blob URL
  const handleSaveQr = () => {
    sounds.playSuccess();
    if (onDownloadQrCode) {
      onDownloadQrCode();
    } else if (hiddenDownloadLinkRef.current) {
      hiddenDownloadLinkRef.current.click();
    } else {
      const link = document.createElement('a');
      link.href = qrBlobUrl || gcashProvider.qrImage;
      link.download = 'MotoCare-GCash-QR.jpg';
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
    }
    setQrSaved(true);
    setTimeout(() => setQrSaved(false), 2500);
  };

  // Tool 3: Generate & Populate Reference Code
  const handleGenerateRef = () => {
    const newRef = `MC-GCASH-${Math.floor(100000 + Math.random() * 900000)}`;
    setAutoGeneratedRef(newRef);
    setReferenceNumber(newRef);
    sounds.playClick();
  };

  // Tool 4: One-Click Copy Reference Code to Clipboard
  const handleCopyRef = () => {
    const refToCopy = referenceNumber.trim() || autoGeneratedRef;
    if (!referenceNumber.trim()) {
      setReferenceNumber(refToCopy);
    }
    navigator.clipboard?.writeText(refToCopy);
    sounds.playClick();
    setCopiedRef(true);
    setTimeout(() => setCopiedRef(false), 2000);
  };

  // Handler for modal Google sign-in
  const handleModalGoogleSignIn = async () => {
    setAuthModalError('');
    setIsAuthProcessing(true);
    try {
      await signIn();
      setIsAuthModalOpen(false);
      sounds.playSuccess();
    } catch {
      setAuthModalError('Google Sign-In was cancelled or failed.');
    } finally {
      setIsAuthProcessing(false);
    }
  };

  // Handler for modal Email/Password sign-in & register
  const handleModalEmailAuth = async (e: React.FormEvent) => {
    e.preventDefault();
    setAuthModalError('');
    setIsAuthProcessing(true);
    try {
      if (authMode === 'signin') {
        await signInWithEmail(authEmail.trim(), authPassword);
      } else {
        await signUpWithEmail(authEmail.trim(), authPassword, authDisplayName.trim() || 'MotoCare Rider');
      }
      setIsAuthModalOpen(false);
      sounds.playSuccess();
    } catch (err: any) {
      const msg = err instanceof Error ? err.message : String(err);
      if (msg.includes('user-not-found') || msg.includes('wrong-password') || msg.includes('invalid-credential')) {
        setAuthModalError('Invalid email or password.');
      } else if (msg.includes('email-already-in-use')) {
        setAuthModalError('An account with this email already exists. Try signing in.');
      } else if (msg.includes('weak-password')) {
        setAuthModalError('Password must be at least 6 characters.');
      } else {
        setAuthModalError(msg || 'Authentication failed. Please verify your details.');
      }
    } finally {
      setIsAuthProcessing(false);
    }
  };

  // Submission handler for admin verification
  const handleSubmitForVerification = async () => {
    setSubmissionError('');

    // If user is not authenticated, show friendly sign-in modal while preserving entered ref
    if (!user) {
      setIsAuthModalOpen(true);
      return;
    }

    setIsSubmitting(true);
    sounds.playClick();

    const finalRef = referenceNumber.trim() || autoGeneratedRef;

    try {
      await onSubmitReference(selectedMethod, finalRef);
      setSubmittedRef(finalRef);
      setHasSubmitted(true);
      sounds.playSuccess();
    } catch (err: any) {
      const msg = err instanceof Error ? err.message : String(err);
      setSubmissionError(msg);
      sounds.playClick();
    } finally {
      setIsSubmitting(false);
    }
  };

  // Submitted / Pending State
  if (hasSubmitted) {
    return (
      <div className="p-5 bg-amber-50 border border-amber-200 rounded-3xl text-left space-y-3.5 animate-in fade-in">
        <div className="flex items-center gap-3">
          <div className="w-10 h-10 rounded-2xl bg-amber-200/80 text-amber-800 flex items-center justify-center shrink-0">
            <Clock className="w-5 h-5 animate-pulse" />
          </div>
          <div>
            <div className="text-sm font-extrabold text-amber-900">
              GCash Payment Reference Submitted
            </div>
            <div className="text-xs text-amber-700 font-semibold">
              Status: Pending Owner Verification
            </div>
          </div>
        </div>

        <div className="p-3.5 bg-white/95 rounded-2xl border border-amber-200/80 text-xs space-y-2 shadow-2xs">
          <div className="flex justify-between items-center">
            <span className="text-slate-500 font-medium">GCash Reference Code:</span>
            <span className="font-mono font-black text-slate-800 text-xs">
              {submittedRef || autoGeneratedRef}
            </span>
          </div>
          <div className="flex justify-between items-center">
            <span className="text-slate-500 font-medium">Amount:</span>
            <span className="font-extrabold text-emerald-700 font-mono text-sm">₱{planAmount}.00</span>
          </div>
          <div className="flex justify-between items-center">
            <span className="text-slate-500 font-medium">Payment Channel:</span>
            <span className="font-bold text-[#007DFE] uppercase">GCASH</span>
          </div>
        </div>

        <p className="text-xs text-amber-800 leading-relaxed">
          Thank you! Your GCash reference has been submitted. Typical verification timeframe: <strong>within 5–15 minutes</strong> (up to 24 hours). The owner will verify your GCash transfer in the separate <strong>Admin Panel</strong> to approve your Pro access.
        </p>

        <div className="pt-1 flex gap-2">
          <button
            type="button"
            onClick={() => setHasSubmitted(false)}
            className="flex-1 py-2.5 bg-white hover:bg-slate-50 text-slate-700 border border-slate-200 rounded-xl font-bold text-xs transition-colors cursor-pointer"
          >
            Submit Another Ref
          </button>
          <button
            type="button"
            onClick={onClose}
            className="flex-1 py-2.5 bg-slate-900 hover:bg-black text-white rounded-xl font-bold text-xs transition-all active:scale-95 shadow-sm cursor-pointer"
          >
            Return to Garage
          </button>
        </div>
      </div>
    );
  }

  return (
    <div className="space-y-4">
      {/* Hidden anchor tag bound to the GCash QR blob object */}
      <a
        ref={hiddenDownloadLinkRef}
        href={qrBlobUrl || gcashProvider.qrImage}
        download="MotoCare-GCash-QR.jpg"
        className="hidden"
        aria-hidden="true"
      />
      {/* GCash QR Display Card */}
      <div className="p-4 sm:p-5 bg-slate-50 border border-slate-200/90 rounded-3xl text-center space-y-4 shadow-xs">
        {/* GCash Header Badge */}
        <div className="flex items-center justify-between pb-2 border-b border-slate-200/70">
          <div className="flex items-center gap-2 text-left">
            <div
              className="w-7 h-7 rounded-lg text-white font-black text-xs flex items-center justify-center shadow-xs"
              style={{ backgroundColor: gcashProvider.brandColor }}
            >
              G
            </div>
            <div>
              <div className="font-extrabold text-xs sm:text-sm text-slate-900 leading-tight">
                Pay with GCash QR
              </div>
              <div className="text-[10px] text-slate-500 font-medium">
                {gcashProvider.tagline}
              </div>
            </div>
          </div>

          <span className="text-[10px] font-bold px-2.5 py-0.5 rounded-full bg-blue-50 text-blue-700 border border-blue-200 flex items-center gap-1 shrink-0">
            <Zap className="w-2.5 h-2.5 fill-blue-600 text-blue-600" />
            <span>GCash Official</span>
          </span>
        </div>

        {/* Large, Unobstructed GCash QR Code Viewport for Easy Mobile Scanning */}
        <div className="space-y-2">
          <div className="mx-auto w-64 h-64 sm:w-72 sm:h-72 bg-white p-4 rounded-2xl border-2 border-[#007DFE]/40 shadow-md flex items-center justify-center">
            <img
              src={gcashProvider.qrImage}
              alt="Official GCash QR Code"
              className="w-full h-full object-contain select-none"
            />
          </div>
          <div className="text-[11px] font-bold text-blue-700 bg-blue-50/90 py-1 px-3 rounded-full mx-auto w-fit border border-blue-200/70 flex items-center justify-center gap-1.5">
            <span>✓ Official GCash InstaPay QRPH • Scan with GCash</span>
          </div>
          {qrSaved && (
            <div className="text-[10px] font-bold text-emerald-700 bg-emerald-50 py-1 px-2.5 rounded-full mx-auto w-fit border border-emerald-200 flex items-center justify-center gap-1">
              <Check className="w-3 h-3 text-emerald-600" />
              <span>GCash QR image downloaded to your device</span>
            </div>
          )}
        </div>

        {/* Payment Amount Banner */}
        <div className="flex items-center justify-between p-3 bg-white rounded-xl border border-slate-200/80 text-xs shadow-2xs">
          <span className="text-slate-600 font-semibold">GCash Payment Amount:</span>
          <div className="font-extrabold text-lg text-slate-900 font-mono flex items-baseline gap-1">
            <span className="text-[#007DFE]">₱{planAmount}.00</span>
            <span className="text-[10px] text-slate-400 font-normal">/ month</span>
          </div>
        </div>

        {/* Instant Mobile Tools: Save QR Image & Pay with GCash */}
        <div className="grid grid-cols-2 gap-2">
          {/* Save QR Image Button */}
          <button
            type="button"
            onClick={handleSaveQr}
            className="py-2.5 px-3 rounded-xl bg-white hover:bg-slate-100 border border-slate-200 text-slate-800 font-bold text-xs flex items-center justify-center gap-1.5 shadow-2xs transition-all active:scale-95 cursor-pointer"
            title="Download GCash QR image to your phone gallery"
          >
            {qrSaved ? <Check className="w-4 h-4 text-emerald-600" /> : <Download className="w-4 h-4 text-[#007DFE]" />}
            <span>Save QR Image</span>
          </button>

          {/* Pay with GCash App Button */}
          <button
            type="button"
            onClick={handleOpenApp}
            className="py-2.5 px-3 rounded-xl bg-[#007DFE] hover:bg-[#0066D6] text-white font-bold text-xs flex items-center justify-center gap-1.5 shadow-sm transition-all active:scale-95 cursor-pointer"
            title="Launch GCash app on this phone"
          >
            <Smartphone className="w-4 h-4 text-white" />
            <span>Pay with GCash</span>
            <ExternalLink className="w-3 h-3 opacity-80" />
          </button>
        </div>

        {/* Simple GCash Payment Instructions */}
        <div className="p-3 bg-white rounded-xl border border-slate-200/80 text-left space-y-1.5 text-[11px] text-slate-600">
          <div className="font-extrabold text-slate-800 text-xs">
            How to Pay with GCash:
          </div>
          <ol className="list-decimal list-inside space-y-1 leading-relaxed">
            <li>Scan the GCash QR code above, or tap <strong>Save QR Image</strong> and upload it in your GCash app.</li>
            <li>Send <strong>₱{planAmount}.00</strong> for your 1-month MotoCare Pro subscription.</li>
            <li>Enter your <strong>GCash Reference Number</strong> below and submit for verification.</li>
          </ol>
        </div>

        {/* GCash Reference Input & Submission */}
        <div className="space-y-2 text-xs text-left pt-1">
          <div className="space-y-1.5">
            <div className="flex items-center justify-between text-[11px]">
              <label className="font-bold text-slate-700">
                GCash Transaction Reference Number:
              </label>
              <button
                type="button"
                onClick={handleGenerateRef}
                className="text-[10px] font-bold text-[#007DFE] hover:underline flex items-center gap-0.5 cursor-pointer"
                title="Generate a unique payment reference number"
              >
                <span>Auto-Generate Ref</span>
              </button>
            </div>
            <div className="flex items-center gap-1.5">
              <input
                type="text"
                value={referenceNumber}
                onChange={(e) => setReferenceNumber(e.target.value)}
                placeholder={`Enter GCash Ref No. (e.g. 104829482)`}
                className="flex-1 bg-white border border-slate-200 rounded-xl px-3 py-2.5 text-xs font-mono font-bold text-slate-800 focus:outline-none focus:border-[#007DFE] focus:ring-1 focus:ring-[#007DFE]/20"
              />
              <button
                type="button"
                onClick={handleCopyRef}
                aria-label="Copy to Clipboard"
                title="Copy to Clipboard"
                className="px-3 py-2.5 rounded-xl bg-white hover:bg-slate-100 border border-slate-200 text-slate-700 font-bold text-[11px] flex items-center gap-1.5 shrink-0 shadow-2xs transition-all active:scale-95 cursor-pointer"
              >
                {copiedRef ? (
                  <>
                    <Check className="w-3.5 h-3.5 text-emerald-600" />
                    <span className="text-emerald-700">Copied!</span>
                  </>
                ) : (
                  <>
                    <Copy className="w-3.5 h-3.5 text-[#007DFE]" />
                    <span>Copy to Clipboard</span>
                  </>
                )}
              </button>
            </div>
            <div className="flex items-center justify-between text-[10px] text-slate-500 px-0.5">
              <span>
                Suggested Reference: <strong className="font-mono text-slate-700">{autoGeneratedRef}</strong>
              </span>
              {copiedRef && (
                <span className="text-emerald-600 font-bold">Reference copied to clipboard</span>
              )}
            </div>
          </div>

          {/* Error Message if duplicate or rejected */}
          {submissionError && (
            <div className="p-3 bg-red-50 border border-red-200 rounded-xl text-red-700 text-xs flex items-start gap-2 text-left animate-in fade-in">
              <AlertCircle className="w-4 h-4 text-red-600 shrink-0 mt-0.5" />
              <div className="space-y-0.5">
                <div className="font-extrabold text-red-900">Submission Blocked</div>
                <div className="text-[11px] leading-relaxed">{submissionError}</div>
              </div>
            </div>
          )}

          {/* User Sign-In Status Indicator */}
          <div className="p-2.5 bg-slate-100 rounded-xl border border-slate-200 text-left text-xs flex items-center justify-between">
            <div className="flex items-center gap-2">
              <UserCheck className={`w-3.5 h-3.5 ${user ? 'text-emerald-600' : 'text-slate-400'}`} />
              <span className="text-slate-600 text-[11px]">
                {user ? (
                  <>
                    Account: <strong className="text-slate-900">{user.email || user.displayName}</strong>
                  </>
                ) : (
                  <span className="text-amber-700 font-semibold">Sign in required to link payment to your account</span>
                )}
              </span>
            </div>
            {!user && (
              <button
                type="button"
                onClick={() => setIsAuthModalOpen(true)}
                className="text-[10px] font-black text-[#FF6B00] hover:underline"
              >
                Sign In
              </button>
            )}
          </div>
        </div>
      </div>

      {/* Submit for Owner Verification Button */}
      <div className="space-y-2">
        <button
          type="button"
          disabled={isSubmitting}
          onClick={handleSubmitForVerification}
          className="w-full py-3.5 bg-[#FF6B00] hover:bg-[#EA580C] text-white rounded-2xl font-black text-sm shadow-lg shadow-[#FF6B00]/25 transition-all active:scale-98 flex items-center justify-center gap-2 disabled:opacity-50 cursor-pointer"
        >
          {isSubmitting ? (
            <>
              <div className="w-4 h-4 border-2 border-white border-t-transparent rounded-full animate-spin" />
              <span>Forwarding Reference to Owner...</span>
            </>
          ) : (
            <>
              <Send className="w-4 h-4" />
              <span>Submit Reference for Admin Verification (₱{planAmount})</span>
            </>
          )}
        </button>

        <div className="flex items-center justify-center gap-1.5 text-[10px] text-slate-400">
          <ShieldCheck className="w-3.5 h-3.5 text-slate-400" />
          <span>Manual verification: Owner approves payment in the separate Admin Console.</span>
        </div>
      </div>

      {/* RIDER AUTHENTICATION MODAL (Triggered when logged out to preserve reference input) */}
      {isAuthModalOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/70 backdrop-blur-sm animate-in fade-in">
          <div className="w-full max-w-sm bg-white rounded-3xl p-6 shadow-2xl space-y-4 text-left border border-slate-200">
            <div className="flex items-center justify-between border-b border-slate-100 pb-3">
              <div>
                <h3 className="font-extrabold text-slate-900 text-sm">
                  {authMode === 'signin' ? 'Sign In to MotoCare' : 'Create MotoCare Account'}
                </h3>
                <p className="text-[10px] text-slate-500">
                  Required to link your PRO subscription to your bike garage.
                </p>
              </div>
              <button
                type="button"
                onClick={() => setIsAuthModalOpen(false)}
                className="p-1 rounded-lg text-slate-400 hover:text-slate-600"
              >
                <X className="w-4 h-4" />
              </button>
            </div>

            {authModalError && (
              <div className="p-2.5 bg-red-50 border border-red-200 rounded-xl text-red-700 text-xs flex items-center gap-2">
                <AlertCircle className="w-4 h-4 text-red-600 shrink-0" />
                <span>{authModalError}</span>
              </div>
            )}

            {/* Quick 1-Click Google Sign In */}
            <button
              type="button"
              disabled={isAuthProcessing}
              onClick={handleModalGoogleSignIn}
              className="w-full py-2.5 bg-slate-900 hover:bg-black text-white font-bold text-xs rounded-xl shadow transition-all flex items-center justify-center gap-2 cursor-pointer disabled:opacity-50"
            >
              <svg className="w-4 h-4" viewBox="0 0 24 24">
                <path fill="#4285F4" d="M22.56 12.25c0-.78-.07-1.53-.2-2.25H12v4.26h5.92c-.26 1.37-1.04 2.53-2.21 3.31v2.77h3.57c2.08-1.92 3.28-4.74 3.28-8.09z"/>
                <path fill="#34A853" d="M12 23c2.97 0 5.46-.98 7.28-2.66l-3.57-2.77c-.98.66-2.23 1.06-3.71 1.06-2.86 0-5.29-1.93-6.16-4.53H2.18v2.84C3.99 20.53 7.7 23 12 23z"/>
                <path fill="#FBBC05" d="M5.84 14.09c-.22-.66-.35-1.36-.35-2.09s.13-1.43.35-2.09V7.06H2.18C1.43 8.55 1 10.22 1 12s.43 3.45 1.18 4.94l2.85-2.22.81-.63z"/>
                <path fill="#EA4335" d="M12 5.38c1.62 0 3.06.56 4.21 1.64l3.15-3.15C17.45 2.09 14.97 1 12 1 7.7 1 3.99 3.47 2.18 7.06l3.66 2.84c.87-2.6 3.3-4.52 6.16-4.52z"/>
              </svg>
              <span>Continue with Google</span>
            </button>

            <div className="flex items-center gap-2 text-[10px] text-slate-400 font-bold uppercase tracking-wider text-center">
              <div className="flex-1 h-px bg-slate-200" />
              <span>or email</span>
              <div className="flex-1 h-px bg-slate-200" />
            </div>

            {/* Email/Password form */}
            <form onSubmit={handleModalEmailAuth} className="space-y-2.5 text-xs">
              {authMode === 'register' && (
                <div>
                  <label className="text-[11px] font-bold text-slate-600 block mb-1">Your Name</label>
                  <input
                    type="text"
                    required
                    value={authDisplayName}
                    onChange={(e) => setAuthDisplayName(e.target.value)}
                    placeholder="e.g. Maria Santos"
                    className="w-full bg-slate-50 border border-slate-200 rounded-xl px-3 py-2 text-slate-800 placeholder:text-slate-400 focus:outline-none focus:border-[#FF6B00]"
                  />
                </div>
              )}

              <div>
                <label className="text-[11px] font-bold text-slate-600 block mb-1">Email</label>
                <input
                  type="email"
                  required
                  value={authEmail}
                  onChange={(e) => setAuthEmail(e.target.value)}
                  placeholder="rider@example.com"
                  className="w-full bg-slate-50 border border-slate-200 rounded-xl px-3 py-2 text-slate-800 placeholder:text-slate-400 focus:outline-none focus:border-[#FF6B00]"
                />
              </div>

              <div>
                <label className="text-[11px] font-bold text-slate-600 block mb-1">Password</label>
                <input
                  type="password"
                  required
                  value={authPassword}
                  onChange={(e) => setAuthPassword(e.target.value)}
                  placeholder="••••••••"
                  className="w-full bg-slate-50 border border-slate-200 rounded-xl px-3 py-2 text-slate-800 placeholder:text-slate-400 focus:outline-none focus:border-[#FF6B00]"
                />
              </div>

              <button
                type="submit"
                disabled={isAuthProcessing}
                className="w-full py-2.5 bg-[#FF6B00] hover:bg-[#EA580C] text-white font-bold text-xs rounded-xl shadow transition-all flex items-center justify-center gap-1.5 cursor-pointer disabled:opacity-50"
              >
                {isAuthProcessing ? (
                  <>
                    <div className="w-3.5 h-3.5 border-2 border-white border-t-transparent rounded-full animate-spin" />
                    <span>Processing...</span>
                  </>
                ) : (
                  <span>{authMode === 'signin' ? 'Sign In & Submit' : 'Create Account & Submit'}</span>
                )}
              </button>
            </form>

            <div className="text-center pt-1 text-[11px] text-slate-500">
              {authMode === 'signin' ? (
                <div>
                  Don&apos;t have an account?{' '}
                  <button
                    type="button"
                    onClick={() => {
                      setAuthMode('register');
                      setAuthModalError('');
                    }}
                    className="text-[#FF6B00] font-bold hover:underline"
                  >
                    Register
                  </button>
                </div>
              ) : (
                <div>
                  Already have an account?{' '}
                  <button
                    type="button"
                    onClick={() => {
                      setAuthMode('signin');
                      setAuthModalError('');
                    }}
                    className="text-[#FF6B00] font-bold hover:underline"
                  >
                    Sign In
                  </button>
                </div>
              )}
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
